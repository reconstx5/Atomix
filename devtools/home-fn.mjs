import { open, go, check, failed } from './lib.mjs';
const { browser, page, errors } = await open();
await go(page, '#/');
await page.waitForSelector('.home-rows .row a.card', { timeout: 15000 });
const first = await page.textContent('.spot-title');
await page.keyboard.press('ArrowDown');
await page.keyboard.press('ArrowDown');
await page.waitForTimeout(150);
for (let i = 0; i < 3; i++) await page.keyboard.press('ArrowRight');
await page.waitForTimeout(700);
const info = await page.evaluate(() => ({ spot: document.querySelector('.spot-title')?.textContent, focused: document.activeElement?.getAttribute('aria-label'), compact: document.querySelector('.home-view')?.classList.contains('is-compact'), view: document.querySelector('.view')?.className }));
check('the spotlight follows the remote', info.spot !== first && info.focused?.startsWith(info.spot), JSON.stringify({ first, ...info }));
check('Home keeps its classes', /home-view/.test(info.view), info.view);
check('past the first row the top area gets smaller', info.compact === true);
await page.keyboard.press('Enter');
await page.waitForTimeout(1500);
check('Enter opens the title', /#\/item\//.test(page.url()), page.url());
await page.goBack();
await page.waitForTimeout(1500);
check('Back returns to Home with rows', await page.locator('.home-rows .row').count() > 0);
check('no page errors', !errors.length, errors.join(' | '));
await browser.close();
process.exit(failed() ? 1 : 0);
