import { open, go, check, failed } from './lib.mjs';
const { browser, page, errors } = await open();
await go(page, '#/lists/2');
await page.waitForSelector('.list-item', { timeout: 15000 });
const order = () => page.$$eval('.list-item', (els) => els.map((e) => e.dataset.id).join(','));
const before = await order();
await page.click('.list-item:first-child [aria-haspopup="dialog"]');
await page.waitForSelector('dialog[open]');
await page.click('dialog[open] >> text=Move down');
await page.waitForTimeout(800);
const after = await order();
const focus = await page.evaluate(() => document.activeElement?.closest('.list-item')?.dataset.id);
check('Move down moves it', after.split(',')[1] === before.split(',')[0], `${before} → ${after}`);
check('the remote stays on the moved item', focus === before.split(',')[0], `focus on ${focus}`);
check('the count and Play follow', /3 titles/.test(await page.textContent('.list-head .muted')));
await page.click(`.list-item[data-id="${before.split(',')[0]}"] [aria-haspopup="dialog"]`);
await page.click('dialog[open] >> text=Move up');
await page.waitForTimeout(800);
check('Move up puts it back', (await order()) === before);
await page.click('.list-head [aria-haspopup="dialog"]');
await page.waitForSelector('dialog[open]');
check('the list menu offers Rename, Share and Delete', /Rename[\s\S]*Share with everyone[\s\S]*Delete/.test(await page.textContent('dialog[open]')));
await page.keyboard.press('Escape');
await go(page, '#/lists');
check('the Lists page shows the Watchlist and the playlist', (await page.locator('.lists-view .card-list').count()) === 2);
check('no page errors', !errors.length, errors.join(' | '));
await browser.close();
process.exit(failed() ? 1 : 0);
